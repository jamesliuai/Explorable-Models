// Build records of the packaged reference host (report §17, §20.1, A51, A59): which packed tarballs and which frontend
// dist a packaged app was built from, kept next to its .app bundle.
//
// `conformance.mjs` writes one record per app right after `tauri build` and copies it into the evidence (`builds`).
// `--no-build` reuses existing apps only when the record still describes them: the executable has the recorded sha256,
// the reference host's installed tarballs (packed-artifacts.json) are the ones the app was built from, and the frontend
// dist the release scenario scans is the one the app embeds. Otherwise the evidence would attribute old binaries to
// newly installed tarballs. Side-effect free apart from the explicit read/write helpers.
//
// Each record also names the reference host SOURCES the app was built from (`sources`: HOST_SOURCE_INPUTS, one sha256
// per file). The working tree is not committed, so a commit and dirty flag cannot say which host.rs a binary holds;
// these per-file digests can. `--no-build` refuses an app whose sources changed since it was built, the runner records
// the sources again at the end of every run, and the release pipeline's native gate compares them with the tree.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export const BUILD_RECORD_SCHEMA = 'study-harness-reference.build-record/1';
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/**
 * The source inputs of both packaged apps, relative to the repository root: the reference host's frontend and Rust
 * host (every file under `src-tauri/src`, test modules included), the policy it embeds with include_str!, its build
 * script, Cargo manifest and lock, Tauri configuration, capabilities and icons, and the contracts crate it links by path
 * together with the JSON Schemas that crate embeds (`index.json` and `*.schema.json`). A directory entry covers every
 * file under it; `match` narrows it to the file names the build reads. Build outputs (`dist`, `.conformance-out`,
 * `src-tauri/target`, `src-tauri/gen`, `src-tauri/permissions/autogenerated`, the crate's `target`) and installed
 * packages (`node_modules`, identified by the tarball records) are not inputs; neither are Finder `.DS_Store` files.
 */
export const HOST_SOURCE_INPUTS = Object.freeze([
  'examples/study-harness-tauri/index.html',
  'examples/study-harness-tauri/package.json',
  'examples/study-harness-tauri/package-lock.json',
  'examples/study-harness-tauri/tsconfig.json',
  'examples/study-harness-tauri/vite.config.mjs',
  'examples/study-harness-tauri/public',
  'examples/study-harness-tauri/src',
  'examples/study-harness-tauri/src-tauri/build.rs',
  'examples/study-harness-tauri/src-tauri/Cargo.toml',
  'examples/study-harness-tauri/src-tauri/Cargo.lock',
  'examples/study-harness-tauri/src-tauri/tauri.conf.json',
  'examples/study-harness-tauri/src-tauri/tauri.conformance.conf.json',
  'examples/study-harness-tauri/src-tauri/capabilities',
  'examples/study-harness-tauri/src-tauri/icons',
  'examples/study-harness-tauri/src-tauri/policy',
  'examples/study-harness-tauri/src-tauri/src',
  'packages/activity/rust/Cargo.toml',
  'packages/activity/rust/Cargo.lock',
  'packages/activity/rust/src',
  { path: 'packages/activity/schema', match: '^(index\\.json|[^/]+\\.schema\\.json)$' },
].map((input) => Object.freeze(typeof input === 'string' ? { path: input } : input)));

/**
 * The reference host sources under `root` (HOST_SOURCE_INPUTS): one `{ path, sha256 }` entry per file, sorted by path,
 * and their digest (sha256 over the sorted `path NUL sha256` lines). An input that does not exist contributes no entry,
 * so removing a file changes the digest like editing one.
 */
export function hostSourceDigest(root, inputs = HOST_SOURCE_INPUTS) {
  const entries = [];
  const add = (full) => entries.push({ path: path.relative(root, full).split(path.sep).join('/'), sha256: sha256(readFileSync(full)) });
  const walk = (folder, match) => {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      const full = path.join(folder, entry.name);
      if (entry.isDirectory()) walk(full, match);
      else if (entry.isFile() && entry.name !== '.DS_Store' && (!match || match.test(entry.name))) add(full);
    }
  };
  for (const input of inputs) {
    const full = path.join(root, input.path);
    if (!existsSync(full)) continue;
    if (statSync(full).isDirectory()) walk(full, input.match ? new RegExp(input.match) : null);
    else add(full);
  }
  entries.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return { digest: `sha256:${sha256(entries.map((entry) => `${entry.path}\0${entry.sha256}`).join('\n'))}`, files: entries.length, entries };
}

/**
 * Files that differ between two host source records (`path (changed|added|removed)`, sorted); every file of `current`
 * when `recorded` holds no entries. Empty when they describe the same sources.
 */
export function sourceChanges(recorded, current) {
  const before = new Map((recorded?.entries ?? []).map((entry) => [entry.path, entry.sha256]));
  const after = new Map((current?.entries ?? []).map((entry) => [entry.path, entry.sha256]));
  return [...new Set([...before.keys(), ...after.keys()])].sort()
    .filter((file) => before.get(file) !== after.get(file))
    .map((file) => `${file} (${!before.has(file) ? 'added' : !after.has(file) ? 'removed' : 'changed'})`);
}

/** At most `limit` changed files for a message, with the number left out. */
export const changeList = (changes, limit = 8) => `${changes.slice(0, limit).join(', ')}${changes.length > limit ? `, and ${changes.length - limit} more` : ''}`;

/** The record file next to a bundle: `<target>/release/bundle/macos/<product>.build-record.json`. */
export const buildRecordPath = (build) => path.join(build.targetDir, 'release/bundle/macos', `${build.product}.build-record.json`);

/** Digest of a directory tree: sha256 over sorted `relative path NUL file sha256` lines; null when it does not exist. */
export function treeDigest(directory) {
  if (!existsSync(directory)) return null;
  const files = [];
  const walk = (folder) => {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      const full = path.join(folder, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) files.push(full);
    }
  };
  walk(directory);
  const lines = files.map((file) => `${path.relative(directory, file).split(path.sep).join('/')}\0${sha256(readFileSync(file))}`).sort();
  return { digest: `sha256:${sha256(lines.join('\n'))}`, files: lines.length };
}

/** Tarball identities in a packed-artifacts record: name, version, sha256, integrity (sorted by name). */
export function tarballSet(packed) {
  return (packed?.packages ?? []).map(({ name, version, sha256: hash, integrity }) => ({ name, version, sha256: hash, integrity })).sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * The record of one build (written right after `tauri build` succeeded). `sources` is the hostSourceDigest the build
 * read: the runner takes it before and after `tauri build` and refuses the build when the two differ.
 */
export function createBuildRecord({ kind, command, builtAt, executable, executableSha256, packed, dist, distDigest, sources }) {
  return {
    schema: BUILD_RECORD_SCHEMA, kind, command, builtAt, executable, executableSha256,
    packed: { packManifest: packed?.packManifest ?? null, packages: tarballSet(packed) },
    frontend: { dist, digest: distDigest?.digest ?? null, files: distDigest?.files ?? 0 },
    sources: sources?.digest ? { inputs: HOST_SOURCE_INPUTS, digest: sources.digest, files: sources.files, entries: sources.entries } : null,
  };
}

export function readBuildRecord(file) {
  try { return JSON.parse(readFileSync(file, 'utf8')); } catch { return null; }
}
export function writeBuildRecord(file, record) {
  writeFileSync(file, `${JSON.stringify(record, null, 2)}\n`);
  return file;
}

/**
 * Why an existing app cannot be reused with `--no-build` (empty when it can): no record, an executable other than the
 * recorded one, installed tarballs other than those it was built from, a frontend dist other than the one it embeds, or
 * reference host sources (`sources`: the current hostSourceDigest) other than those it was built from.
 */
export function noBuildProblems({ kind, record, executableSha256, packed, distDigest, sources }) {
  if (!record || record.schema !== BUILD_RECORD_SCHEMA) return [`${kind}: no build record next to the app (built outside conformance.mjs or before build records existed); rebuild without --no-build`];
  const problems = [];
  if (record.kind !== kind) problems.push(`${kind}: the build record describes a ${record.kind} build`);
  if (!executableSha256 || record.executableSha256 !== executableSha256) problems.push(`${kind}: the packaged executable (sha256 ${executableSha256 ?? 'missing'}) is not the one the build record describes (${record.executableSha256 ?? 'none'}); it was rebuilt outside conformance.mjs`);
  const built = new Map((record.packed?.packages ?? []).map((item) => [item.name, item.sha256]));
  const installed = new Map(tarballSet(packed).map((item) => [item.name, item.sha256]));
  const differing = [...new Set([...built.keys(), ...installed.keys()])].sort()
    .filter((name) => built.get(name) !== installed.get(name))
    .map((name) => `${name} built ${built.get(name)?.slice(0, 12) ?? 'absent'}, installed ${installed.get(name)?.slice(0, 12) ?? 'absent'}`);
  if (!built.size) problems.push(`${kind}: the build record names no packed tarballs`);
  if (differing.length) problems.push(`${kind}: the installed tarballs (packed-artifacts.json) differ from those the app was built from (${differing.join('; ')})`);
  if (!record.frontend?.digest || record.frontend.digest !== distDigest?.digest) problems.push(`${kind}: the frontend dist (${distDigest?.digest ?? 'missing'}) is not the one the app embeds (${record.frontend?.digest ?? 'unrecorded'})`);
  if (!record.sources?.digest) problems.push(`${kind}: the build record does not name the reference host sources the app was built from (recorded before source identities existed)`);
  else if (record.sources.digest !== sources?.digest) problems.push(`${kind}: the reference host sources changed since the app was built (${changeList(sourceChanges(record.sources, sources)) || `digest ${sources?.digest ?? 'missing'}`})`);
  return problems;
}
