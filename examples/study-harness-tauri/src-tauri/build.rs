/// tauri-build writes one permission file per manifest command into `permissions/autogenerated/` and never removes
/// files of commands that are no longer listed. Release and conformance builds share this directory, so stale files
/// (conformance commands, or earlier spike commands) are pruned before each build: the release ACL then defines
/// permissions for production commands only.
fn prune_stale_permissions(commands: &[&str]) {
    let Ok(entries) = std::fs::read_dir("permissions/autogenerated") else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let Some(stem) = path.file_stem().and_then(|stem| stem.to_str()) else { continue };
        let generated = std::fs::read_to_string(&path).is_ok_and(|text| text.starts_with("# Automatically generated - DO NOT EDIT!"));
        if path.extension().is_some_and(|extension| extension == "toml") && generated && !commands.contains(&stem) {
            std::fs::remove_file(&path).expect("failed to prune a stale autogenerated permission file");
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed=policy/approved.json");
    println!("cargo:rerun-if-changed=capabilities");
    let commands = if std::env::var_os("CARGO_FEATURE_CONFORMANCE").is_some() { CONFORMANCE_COMMANDS } else { PRODUCTION_COMMANDS };
    prune_stale_permissions(commands);
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(commands)))
        .expect("failed to run tauri-build");
}
