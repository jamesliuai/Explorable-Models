/**
 * Builds the installed index of `@experiment-kit/catalog` (src/installed-index.ts, read by `createLazyCatalog`) from the
 * installed content through the eager catalogue, so every reference, identity and discovery entry is computed from
 * content — never written by hand — and only content that passes the catalogue's own validation is indexed.
 * Used by scripts/study-harness/generate-catalog-index.mjs (write / --check) and tests/catalog/lazy.test.ts. Not part of
 * the published package (outside src).
 */
import { fileURLToPath } from 'node:url';
import { CONTENT_LOADERS } from '../src/content/loaders.js';
import type { IndexedModelEntry, IndexedTemplateEntry, InstalledIndex } from '../src/index-types.js';
import { createInstalledCatalog } from '../src/installed.js';
import { INSTALLED_KERNELS } from '../src/kernels/index.js';
import { INSTALLED_MODELS } from '../src/models/index.js';

export const INSTALLED_INDEX_PATH = fileURLToPath(new URL('../src/installed-index.ts', import.meta.url));
export const GENERATED_BY = 'scripts/study-harness/generate-catalog-index.mjs';

export function buildInstalledIndex(): InstalledIndex {
  const catalog = createInstalledCatalog({ workerFactory: () => { throw new Error('No worker is created while indexing.'); } });
  const problems = catalog.problems();
  if (problems.length) throw new Error(`Installed content fails validation; nothing is indexed: ${JSON.stringify(problems).slice(0, 2000)}`);
  const templates: IndexedTemplateEntry[] = catalog.listTemplates().map(entry => ({
    ref: { ...entry.template }, model: { modelId: entry.model.modelId, version: entry.model.version }, title: entry.title, dimension: entry.dimension,
    discovery: catalog.describe(entry.template)!,
  }));
  const models: IndexedModelEntry[] = INSTALLED_MODELS.map(input => {
    const identity = catalog.identity({ modelId: input.modelId, version: input.version });
    if (!identity || identity.kind !== 'model') throw new Error(`Model ${input.modelId}@${input.version} is not served.`);
    const execution = catalog.getModel(identity.model)!.execution;
    const kernel = execution.kind === 'kernel' ? INSTALLED_KERNELS.find(item => item.id === execution.kernelId && item.version === execution.kernelVersion)! : null;
    return { ref: identity.model, identity: identity.identity, referenceSuiteDigest: input.referenceSuite?.digest ?? null, kernel: kernel ? { id: kernel.id, version: kernel.version, mode: kernel.mode } : null };
  });
  const keys = templates.map(entry => `${entry.ref.templateId}@${entry.ref.version}`);
  const bundled = Object.keys(CONTENT_LOADERS);
  if (keys.some(item => !bundled.includes(item)) || bundled.some(item => !keys.includes(item)))
    throw new Error(`Content loaders (${bundled.join(', ')}) must cover exactly the installed templates (${keys.join(', ')}).`);
  return { generatedBy: GENERATED_BY, kernels: INSTALLED_KERNELS.map(kernel => ({ id: kernel.id, version: kernel.version, mode: kernel.mode })), models, templates };
}

/** TypeScript source of src/installed-index.ts for an index. */
export function renderInstalledIndex(index: InstalledIndex): string {
  return [
    `// GENERATED by ${GENERATED_BY} from the installed content (through the eager catalogue's validation). Do not edit:`,
    '// after changing a template, learner copy, model manifest, kernel identity or content loader, run',
    '// `node scripts/study-harness/generate-catalog-index.mjs`. tests/catalog/lazy.test.ts fails while this file is stale, and',
    '// createLazyCatalog() refuses content that does not reproduce these digests.',
    "import { deepFreeze } from '@experiment-kit/core';",
    "import type { InstalledIndex } from './index-types.js';",
    '',
    `export const INSTALLED_INDEX: InstalledIndex = deepFreeze(${JSON.stringify(index, null, 2)} as InstalledIndex);`,
    '',
  ].join('\n');
}
