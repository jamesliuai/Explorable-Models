export function parseResumeArgs(argv) {
  const options = { check: false };
  for (const arg of argv) {
    if (arg === '--check') { assert(!options.check, 'Duplicate --check'); options.check = true; continue; }
    const match = /^--(parent|checkpoint|plan)=(.+)$/.exec(arg);
    assert(match && !options[match[1]], `Unknown or duplicate resume argument: ${arg}`);
    options[match[1]] = match[2];
  }
  assert(options.parent && options.checkpoint && options.plan, 'Required: --parent=<immutable history> --checkpoint=<source checkpoint> --plan=<reviewed change plan> [--check]');
  return options;
}

export function validateParent(parent) {
  assert(parent?.schema === SCHEMA && parent.partial === false && parent.selection?.only === null && parent.selection?.skip === null, 'Resume requires a completed full parent, never a partial/selected run');
  assert(!parent.resume, 'Resume from a fresh full parent, not another resumed record');
  assert(['pass', 'fail'].includes(parent.status) && Number.isFinite(Date.parse(parent.generatedAt)), 'Parent did not complete');
  assert.deepEqual(parent.gates.map(row => row.id), [...STEP_IDS], 'Parent must contain every required gate exactly once, in order');
  assert.deepEqual(parent.summary, summarize(parent.gates), 'Parent gate summary is inconsistent');
  assert.equal(overallStatus(parent.gates, false), parent.status, 'Parent overall status is inconsistent');
  assert.equal(parent.releaseEvidence, parent.status === 'pass', 'Parent release-evidence flag is inconsistent');
  assert(parent.pack?.complete === true && parent.pack.packages?.length === 6 && HEX.test(parent.pack.manifestSha256), 'Parent has no complete six-package identity');
  assert.equal(new Set(parent.pack.packages.map(row => row.name)).size, 6, 'Parent pack has duplicate names');
  assert.equal(parent.gates[0].status, STATUS.pass, 'Parent pack failed');
  assert.equal(parent.gates[0].manifestSha256, parent.pack.manifestSha256, 'Parent pack gate identity differs');
  assert(parent.packageLock?.sha256 === parent.pack.lockSha256 && HEX.test(parent.packageLock.sha256), 'Parent root lock differs from its pack');
  for (const row of parent.gates) {
    assert([STATUS.pass, STATUS.fail].includes(row.status), `Parent has an unexecuted gate: ${row.id}`);
    if (row.id !== 'pack') assert.equal(row.pack, parent.pack.manifestSha256, `Parent gate used another pack: ${row.id}`);
    if (!RERUN_GATES.includes(row.id)) assert.equal(row.status, STATUS.pass, `Unchanged gate did not pass in parent: ${row.id}`);
    if (row.status === STATUS.pass && row.segments?.length) assert.equal(gateOutcome(row.segments).status, STATUS.pass, `Parent segment result is inconsistent: ${row.id}`);
  }
  assert.equal(parent.gates.find(row => row.id === 'release').status, STATUS.pass, 'Parent has no original source archive');
  return parent;
}

/** Read regular members without extracting files. npm tarballs use ustar/PAX; long paths remain fully identified. */
export function readArchive(bytes) {
  const tar = gunzipSync(bytes), files = new Map();
  let next = {}, global = {}, longName = null;
  const text = buffer => buffer.toString('utf8').replace(/\0.*$/s, '');
  for (let offset = 0; offset + 512 <= tar.length;) {
    const header = tar.subarray(offset, offset + 512);
    if (header.every(value => value === 0)) break;
    const size = parseInt(text(header.subarray(124, 136)).trim() || '0', 8);
    assert(Number.isSafeInteger(size) && size >= 0 && offset + 512 + size <= tar.length, 'Invalid source archive member size');
    const body = tar.subarray(offset + 512, offset + 512 + size), type = text(header.subarray(156, 157));
    offset += 512 + Math.ceil(size / 512) * 512;
    if (type === 'x' || type === 'g') {
      const fields = {};
      for (let i = 0; i < body.length;) {
        const space = body.indexOf(32, i), length = Number(body.subarray(i, space).toString());
        assert(space > i && Number.isSafeInteger(length) && length > space - i && i + length <= body.length, 'Invalid PAX record');
        const record = body.subarray(space + 1, i + length - 1).toString('utf8'), equals = record.indexOf('=');
        fields[record.slice(0, equals)] = record.slice(equals + 1); i += length;
      }
      if (type === 'g') global = { ...global, ...fields }; else next = fields;
      continue;
    }
    if (type === 'L') { longName = text(body); continue; }
    const prefix = text(header.subarray(345, 500));
    const name = next.path ?? global.path ?? longName ?? `${prefix ? `${prefix}/` : ''}${text(header.subarray(0, 100))}`;
    next = {}; longName = null;
    if (type && type !== '0') continue;
    assert(name.startsWith('package/') && relativePath(name), `Unsafe source archive member: ${name}`);
    const file = name.slice('package/'.length);
    assert(!files.has(file), `Duplicate source archive member: ${file}`);
    files.set(file, { sha256: sha256Hex(body), bytes: body });
  }
  assert(files.size > 0, 'Source archive has no files');
  return files;
}

export function sourceFiles(root) {
  const files = [...ROOT_FILES];
  const walk = relative => {
    for (const entry of readdirSync(path.join(root, relative), { withFileTypes: true })) {
      if (entry.name.startsWith('.') || IGNORED.has(entry.name)) continue;
      const file = `${relative}/${entry.name}`;
      assert(!entry.isSymbolicLink(), `Source symlink is not resumable: ${file}`);
      if (entry.isDirectory()) walk(file);
      else if (entry.isFile() && (/\.(?:ts|tsx|js|mjs|json|css|html|svg|rs|toml|lock)$/.test(entry.name) || ['LICENSE', 'model.md'].includes(entry.name))) files.push(file);
    }
  };
  for (const directory of SOURCE_ROOTS) walk(directory);
  return files.sort().map(file => { assert(!lstatSync(at(root, file)).isSymbolicLink(), `Source symlink: ${file}`); return { path: file, sha256: sha256Hex(readFileSync(at(root, file))) }; });
}

export function validateChanges({ before, current, plan, archive = new Map(), allowGeneratedNative = false }) {
  const baseline = new Map(before.map(row => [row.path, row.sha256])), actual = new Map(current.map(row => [row.path, row.sha256]));
  assert.equal(baseline.size, before.length, 'Duplicate checkpoint source path');
  assert.equal(actual.size, current.length, 'Duplicate current source path');
  assert(Array.isArray(plan.changes) && plan.changes.length > 0, 'A reviewed change plan is required');
  const reviewed = new Map();
  for (const change of plan.changes) {
    assert(relativePath(change.path) && REVIEWABLE_PATHS[change.path] === change.kind, `Unapproved change path/kind: ${change.path}`);
    assert(!reviewed.has(change.path), `Duplicate reviewed change: ${change.path}`);
    assert(typeof change.reason === 'string' && change.reason.trim().length >= 10, `Missing review reason: ${change.path}`);
    const previous = baseline.get(change.path) ?? archive.get(change.path)?.sha256 ?? null;
    assert.equal(change.beforeSha256, previous, `Reviewed before hash differs: ${change.path}`);
    assert(HEX.test(change.afterSha256) && change.afterSha256 === actual.get(change.path), `Reviewed after hash differs: ${change.path}`);
    assert.notEqual(change.beforeSha256, change.afterSha256, `Reviewed file did not change: ${change.path}`);
    reviewed.set(change.path, change);
  }
  const changes = [];
  for (const file of new Set([...baseline.keys(), ...actual.keys()])) {
    const oldHash = baseline.get(file) ?? archive.get(file)?.sha256 ?? null, newHash = actual.get(file) ?? null;
    if (oldHash === newHash) continue;
    if (allowGeneratedNative && file === GENERATED_NATIVE) continue;
    assert(reviewed.has(file), `Unreviewed source change: ${file}`);
    assert(newHash !== null, `Source removal is not resumable: ${file}`);
    changes.push({ path: file, beforeSha256: oldHash, afterSha256: newHash });
  }
  for (const file of reviewed.keys()) assert(changes.some(row => row.path === file), `Reviewed file is outside audited source scope: ${file}`);
  return changes;
}

export function verifyPack(root, parent) {
  const manifestFile = at(root, parent.pack.manifest), bytes = readFileSync(manifestFile), manifest = JSON.parse(bytes);
  assert.equal(sha256Hex(bytes), parent.pack.manifestSha256, 'Pack manifest bytes changed');
  assert(manifest.complete && manifest.packages.length === 6, 'Current pack is incomplete');
  assert.equal(sha256Hex(readFileSync(at(root, 'package-lock.json'))), parent.packageLock.sha256, 'Root dependency lock changed');
  for (const expected of parent.pack.packages) {
    const item = manifest.packages.find(row => row.name === expected.name);
    for (const key of ['file', 'sha256', 'integrity', 'version', 'bytes']) assert.equal(item?.[key], expected[key], `Pack identity differs: ${expected.name}.${key}`);
    const content = readFileSync(at(root, `${path.posix.dirname(parent.pack.manifest)}/${expected.file}`));
    assert.equal(sha256Hex(content), expected.sha256, `Actual tarball changed: ${expected.name}`);
    assert.equal(content.length, expected.bytes, `Actual tarball size changed: ${expected.name}`);
  }
  return manifest;
}

export function evaluateConsumer(evidence, pack, budgets) {
  assert(evidence?.ok && evidence.checks?.length > 0 && evidence.checks.every(row => row.ok === true), 'Consumer recorded failed or missing checks');
  const identity = compareTarballs(pack, evidence.pack?.packages);
  assert(identity.compared === pack.length && !identity.mismatches.length, 'Consumer used different tarballs');
  const raw = evidence.budgets, limits = budgets.dependency;
  assert(raw.legacy2dConsumer.gzipBytes > 0 && raw.legacy2dConsumer.gzipBytes <= limits.legacy2dConsumer.maxGzipBytes, 'Consumer legacy raw budget fails');
  for (const entry of limits.activityEntry.entries) {
    const row = raw.activityEntry[entry];
    assert(row?.gzip9 > 0 && row.gzip9 <= limits.activityEntry.maxGzipBytes && row.chunks?.some(chunk => chunk.worker), `Consumer activity raw budget fails: ${entry}`);
    assert.equal(row.chunks.reduce((sum, chunk) => sum + chunk.gzip9, 0), row.gzip9, `Consumer activity chunk total differs: ${entry}`);
    assert(row.inlineScripts === 0 && row.forbiddenSources?.length === 0 && row.forbiddenTextMarkers?.length === 0, `Consumer eager graph is not clean: ${entry}`);
  }
  const within = (value, limit) => value?.bytes > 0 && value.bytes <= limit.maxBytes && (limit.maxGzipBytes === undefined || value.gzip9 > 0 && value.gzip9 <= limit.maxGzipBytes);
  for (const part of ['js', 'css', 'fonts']) assert(within(raw.lazy.math[part], limits.lazyMath[part]), `Consumer math raw budget fails: ${part}`);
  assert(within(raw.lazy.uiFonts, limits.bundledUiFonts), 'Consumer UI font raw budget fails');
  assert(within(raw.lazy.spatial, limits.lazy3d.js), 'Consumer spatial raw budget fails');
  const content = raw.catalogueContent;
  assert(content.templatesCopyModels === 0 && content.kernelCodeInPage === 0 && content.chunks.length === 5 && content.total > 0 && content.total <= limits.catalogueContent.maxBytes, 'Consumer catalogue raw budget fails');
  return { status: STATUS.pass, checks: evidence.checks.length, rawBudgetsReevaluated: true };
}

function immutableEvidence(root, kind, evidence, gate) {
  const dateKey = kind === 'performance' || kind === 'consumer' ? 'createdAt' : 'generatedAt';
  assert(Date.parse(evidence[dateKey]) >= Date.parse(gate.startedAt) && Date.parse(evidence[dateKey]) <= Date.parse(gate.startedAt) + gate.durationMs + 1000, `${kind} evidence is outside its parent gate`);
  // The benchmark adds its history link after the immutable record is written. Only that index pointer differs.
  const { history: historyPointer, ...measuredEvidence } = evidence;
  const matches = readdirSync(at(root, `${EVIDENCE}/history`)).filter(file => file.startsWith(`${kind}-`) && file.endsWith('.json')).map(file => `${EVIDENCE}/history/${file}`).filter(file => {
    const envelope = json(at(root, file));
    const { history: _pointer, ...record } = envelope.record ?? {};
    return envelope.kind === kind && digestJSON(record) === digestJSON(measuredEvidence);
  });
  assert.equal(matches.length, 1, `${kind} evidence does not match one immutable parent history record`);
  if (historyPointer) assert.equal(`${EVIDENCE}/${historyPointer}`, matches[0], `${kind} history pointer differs`);
  return { path: matches[0], sha256: sha256Hex(readFileSync(at(root, matches[0]))) };
}

function nativeBaseline(root, parent, checkpoint) {
  const bytes = readFileSync(at(root, `${EVIDENCE}/native-conformance.json`)), evidence = JSON.parse(bytes), gate = parent.gates.find(row => row.id === 'native');
  assert.equal(evidence.generatedAt, gate.details?.evidenceGeneratedAt, 'Native evidence differs from parent');
  const sources = evidence.builds?.release?.sources;
  assert(sources?.entries?.length > 0 && sources.digest === gate.details.sources.builtFrom && sources.digest === evidence.builds.conformance.sources.digest, 'Parent native source identity is incomplete');
  assert.equal(sources.digest, `sha256:${sha256Hex(sources.entries.map(row => `${row.path}\0${row.sha256}`).join('\n'))}`, 'Parent native source entries do not match their digest');
  assert.deepEqual(evidence.builds.conformance.sources.entries, sources.entries, 'Parent native builds have different source entries');
  const expected = new Map(checkpoint.files.map(row => [row.path, row.sha256]));
  for (const row of sources.entries) if (expected.has(row.path)) assert.equal(row.sha256, expected.get(row.path), `Native source checkpoint mismatch: ${row.path}`);
  for (const [name, binary] of Object.entries(evidence.binaries ?? {})) {
    assert.equal(binary.sha256, gate.details.binaries[name]?.recorded, `Parent native binary evidence differs: ${name}`);
    assert.equal(sha256Hex(readFileSync(at(root, binary.executable))), binary.sha256, `Parent native binary changed: ${name}`);
  }
  assert.deepEqual(Object.keys(evidence.binaries).sort(), ['conformance', 'release']);
  return { evidence, sha256: sha256Hex(bytes), path: `${EVIDENCE}/native-conformance.json` };
}

export function auditResume({ root = ROOT, parentPath, checkpointPath, planPath }) {
  const historyFile = path.resolve(root, parentPath), parentBytes = readFileSync(historyFile), envelope = JSON.parse(parentBytes);
  assert(!envelope.terminologyProjection, 'Terminology-normalized historical evidence cannot be resumed; use the original evidence bytes or a fresh full run');
  const historyRelative = path.relative(root, historyFile).split(path.sep).join('/');
  assert([`${EVIDENCE}/history/verification-`, `${OUT}/history/verification-`].some(prefix => historyRelative.startsWith(prefix)) && relativePath(historyRelative), 'Parent must be an append-only verification-history path');
  assert(envelope.schema === 'study-harness.evidence-history/1' && envelope.kind === 'verification', 'Parent must be immutable verification history');
  const parent = validateParent(envelope.record), checkpointBytes = readFileSync(path.resolve(root, checkpointPath)), checkpoint = JSON.parse(checkpointBytes), planBytes = readFileSync(path.resolve(root, planPath)), plan = JSON.parse(planBytes);
  assert(checkpoint.schema === 'study-harness.resume-source-checkpoint/1' && checkpoint.parentRunId === parent.runId, 'Checkpoint belongs to another run');
  assert(Date.parse(checkpoint.createdAt) >= Date.parse(parent.generatedAt), 'Checkpoint predates the completed parent');
  assert.equal(checkpoint.parentRecordSha256, sha256Hex(`${JSON.stringify(parent, null, 2)}\n`), 'Checkpoint does not identify the immutable parent record');
  assert.equal(checkpoint.digest, digestJSON(checkpoint.files), 'Checkpoint source digest is invalid');
  assert(plan.schema === PLAN_SCHEMA && plan.parentRunId === parent.runId, 'Change plan belongs to another run');
  assert(typeof plan.review === 'string' && plan.review.trim().length >= 10, 'Change plan must record its review provenance');
  assert.equal(plan.checkpointSha256, sha256Hex(checkpointBytes), 'Change plan identifies another checkpoint');
  const release = parent.gates.find(row => row.id === 'release').details, original = checkpoint.sourceArchive;
  assert.equal(original.sha256, release.sha256, 'Original archive differs from parent release');
  const archiveBytes = readFileSync(at(root, original.path));
  assert.equal(`sha256:${sha256Hex(archiveBytes)}`, original.sha256, 'Preserved original source archive changed');
  const archive = readArchive(archiveBytes), manifest = verifyPack(root, parent);
  // The unified source package transforms its root package/lock and regenerates revision/public files in staging.
  // Those explicit derived exceptions remain pinned by the source checkpoint and root pack/lock identities.
  const derived = file => file === 'package.json' || file === 'package-lock.json' || file === 'examples/revisions.ts' || file.startsWith('public/source') || file === GENERATED_NATIVE || file === NATIVE_LOCK || file === NATIVE_APPROVED_POLICY;
  let archiveCompared = 0;
  for (const row of checkpoint.files) {
    if (derived(row.path)) continue;
    const member = archive.get(row.path);
    assert(member && member.sha256 === row.sha256, `Original source archive/checkpoint mismatch: ${row.path}`); archiveCompared++;
  }
  const native = nativeBaseline(root, parent, checkpoint);
  const extraNative = native.evidence.builds.release.sources.entries.filter(row => !checkpoint.files.some(file => file.path === row.path));
  const current = sourceFiles(root);
  for (const row of extraNative) if (!current.some(file => file.path === row.path)) current.push({ path: row.path, sha256: sha256Hex(readFileSync(at(root, row.path))) });
  for (const change of plan.changes ?? []) if (change.path === 'docs/release.md') current.push({ path: change.path, sha256: sha256Hex(readFileSync(at(root, change.path))) });
  current.sort((a, b) => a.path.localeCompare(b.path));
  validateChanges({ before: [...checkpoint.files, ...extraNative], current, plan, archive });
  const pipeline = 'scripts/study-harness/release-pipeline.mjs';
  const removeExports = text => text.replace(/^export (?=(?:async )?function (?:browserEnvironment|runCommandGate|afterGate|runNative|claims)\()/gm, '');
  assert.equal(removeExports(readFileSync(at(root, pipeline), 'utf8')), removeExports(archive.get(pipeline).bytes.toString()), 'Existing release pipeline behavior changed beyond helper exports');
  const budgets = json(at(root, 'docs/study-harness/budgets.json'));
  assert.equal(sha256Hex(readFileSync(at(root, 'docs/study-harness/budgets.json'))), archive.get('docs/study-harness/budgets.json')?.sha256, 'Budget rules changed');
  const consumer = json(at(root, `${EVIDENCE}/consumer.json`)), performance = json(at(root, `${EVIDENCE}/performance.json`));
  const consumerGate = parent.gates.find(row => row.id === 'verify:consumer'), benchmarkGate = parent.gates.find(row => row.id === 'benchmark');
  const consumerHistory = immutableEvidence(root, 'consumer', consumer, consumerGate), performanceHistory = immutableEvidence(root, 'performance', performance, benchmarkGate);
  const consumerAudit = evaluateConsumer(consumer, parent.pack.packages, budgets), benchmarkAudit = evaluateBenchmarkEvidence({ evidence: performance, pack: parent.pack.packages, budgets });
  assert.equal(consumerAudit.checks, consumerGate.counts.total, 'Consumer check count differs from parent');
  assert.equal(benchmarkAudit.status, STATUS.pass, `Parent benchmark no longer passes raw evaluation: ${benchmarkAudit.reason}`);
  const derivedArchiveExceptions = checkpoint.files.filter(row => derived(row.path)).map(row => ({ path: row.path, checkpointSha256: row.sha256, archivedSha256: archive.get(row.path)?.sha256 ?? null, reason: row.path === NATIVE_LOCK ? 'The source-release gate precedes the parent native installer; the installer updates the native dependency lock to the exact packed tarball integrities.' : row.path === NATIVE_APPROVED_POLICY ? 'The source-release gate precedes the parent native build; generate-approved-policy writes the exact installed template approvals before that build.' : 'The unified source stage transforms package/lock and regenerates revision/public-source files; the native install record is derived from the exact pack.', boundBy: [NATIVE_LOCK, NATIVE_APPROVED_POLICY].includes(row.path) ? 'parent native build source entries and frozen current source' : 'source checkpoint and pack/lock identity; staging or native-install generated' }));
  const provenance = { parent: { runId: parent.runId, status: parent.status, history: path.relative(root, historyFile), historySha256: sha256Hex(parentBytes), recordSha256: checkpoint.parentRecordSha256 }, checkpoint: { path: path.relative(root, path.resolve(root, checkpointPath)), sha256: sha256Hex(checkpointBytes), sourceDigest: checkpoint.digest }, plan: { path: path.resolve(root, planPath), sha256: sha256Hex(planBytes), changes: plan.changes }, sourceArchive: { ...original, comparedFiles: archiveCompared, derivedExceptions: derivedArchiveExceptions }, source: { files: current.length, digest: digestJSON(current) }, consumer: { ...consumerHistory, ...consumerAudit }, benchmark: { ...performanceHistory, ...benchmarkAudit }, native: { evidenceSha256: native.sha256, sources: native.evidence.builds.release.sources, binaries: native.evidence.binaries } };
  const frozenFiles = [historyFile, path.resolve(root, checkpointPath), path.resolve(root, planPath), at(root, original.path), at(root, 'docs/study-harness/budgets.json'), at(root, `${EVIDENCE}/consumer.json`), at(root, `${EVIDENCE}/performance.json`), at(root, consumerHistory.path), at(root, performanceHistory.path)];
  for (const row of parent.gates.filter(row => !RERUN_GATES.includes(row.id))) {
    assert(row.log?.startsWith(`${OUT}/logs/${parent.runId}/`), `Parent reused gate has no original log: ${row.id}`);
    frozenFiles.push(at(root, row.log));
    for (const segment of row.segments ?? []) if (segment.report) {
      assert(segment.report.startsWith(`${OUT}/logs/${parent.runId}/`), `Parent report is outside the original run: ${row.id}`);
      frozenFiles.push(at(root, segment.report));
    }
  }
  return { parent, checkpoint, plan, current, extraNative, manifest, native, provenance, inputFiles: frozenFiles.map(file => ({ path: file, sha256: sha256Hex(readFileSync(file)) })) };
}

export function reusedGate(row, provenance, root = ROOT) {
  assert.equal(row.status, STATUS.pass, `Cannot reuse failed gate: ${row.id}`);
  const log = row.log ? { path: row.log, sha256: sha256Hex(readFileSync(at(root, row.log))) } : null;
  const reports = (row.segments ?? []).filter(segment => segment.report).map(segment => ({ path: segment.report, sha256: sha256Hex(readFileSync(at(root, segment.report))) }));
  return { ...structuredClone(row), execution: 'reused', reusedFrom: { ...provenance.parent, gateId: row.id, gateRecordSha256: digestJSON(row), log, reports, startedAt: row.startedAt ?? null, durationMs: row.durationMs ?? null } };
}

function ensureFrozen(audit) {
  for (const input of audit.inputFiles) assert.equal(sha256Hex(readFileSync(input.path)), input.sha256, `Resume input changed during verification: ${input.path}`);
  const current = sourceFiles(ROOT);
  for (const row of audit.extraNative) if (!current.some(file => file.path === row.path)) current.push({ path: row.path, sha256: sha256Hex(readFileSync(at(ROOT, row.path))) });
  if (audit.plan.changes.some(row => row.path === 'docs/release.md')) current.push({ path: 'docs/release.md', sha256: sha256Hex(readFileSync(at(ROOT, 'docs/release.md'))) });
  const before = audit.current.filter(row => row.path !== GENERATED_NATIVE), after = current.filter(row => row.path !== GENERATED_NATIVE);
  assert.deepEqual(after.sort((a, b) => a.path.localeCompare(b.path)), before.sort((a, b) => a.path.localeCompare(b.path)), 'Audited source changed during resume');
  verifyPack(ROOT, audit.parent);
  const installed = json(at(ROOT, GENERATED_NATIVE)), compare = compareTarballs(audit.parent.pack.packages, installed.packages);
  assert(compare.compared === 5 && compare.mismatches.length === 0, 'Native installer selected another pack');
  const nativeLock = json(at(ROOT, NATIVE_LOCK));
  for (const row of installed.packages) assert.equal(nativeLock.packages?.[`node_modules/${row.name}`]?.integrity, audit.manifest.packages.find(item => item.name === row.name)?.integrity, `Native install integrity differs: ${row.name}`);
}

export async function main(argv = process.argv.slice(2)) {
  const options = parseResumeArgs(argv), audit = auditResume({ parentPath: options.parent, checkpointPath: options.checkpoint, planPath: options.plan });
  if (options.check) { console.log(JSON.stringify({ check: 'pass', parent: audit.provenance.parent, sourceChanges: audit.provenance.plan.changes, rerun: RERUN_GATES, reuse: STEP_IDS.filter(id => !RERUN_GATES.includes(id)), archiveCompared: audit.provenance.sourceArchive.comparedFiles }, null, 2)); return { exitCode: 0, audit }; }
  const started = Date.now(), runId = stamp(new Date(started)), logDir = at(ROOT, `${OUT}/logs/${runId}`);
  mkdirSync(logDir, { recursive: true });
  writeFileSync(path.join(logDir, 'resume-audit.json'), `${JSON.stringify(audit.provenance, null, 2)}\n`, { flag: 'wx' });
  writeFileSync(path.join(logDir, 'parent-native-evidence.json'), `${JSON.stringify(audit.native.evidence, null, 2)}\n`, { flag: 'wx' });
  const environment = { tools: toolVersions(ROOT), platform: platformIdentity(), browsers: await browserEnvironment(), consoleLocked: consoleLocked() };
  assert.deepEqual(environment.tools, audit.parent.tools, 'Tool versions changed since parent');
  for (const [name, browser] of Object.entries(audit.parent.browsers)) assert.equal(environment.browsers[name]?.version, browser.version, `Browser version changed: ${name}`);
  assert.equal(environment.platform.os.version, audit.parent.platform.os.version, 'OS version changed since parent');
  const scripts = json(at(ROOT, 'package.json')).scripts, results = new Map();
  const say = message => console.log(`[release-resume] ${message}`);
  say(`run ${runId}; resumed full-candidate verification from ${audit.parent.runId}; unchanged six-package pack ${audit.parent.pack.manifestSha256}`);
  for (const row of audit.parent.gates) if (!RERUN_GATES.includes(row.id)) results.set(row.id, reusedGate(row, audit.provenance));
  for (const id of RERUN_GATES) {
    const gate = GATES.find(row => row.id === id), gateStart = Date.now();
    ensureFrozen(audit);
    const missing = (gate.requires ?? []).map(requirement => missingRequirement(requirement, environment)).filter(Boolean);
    let outcome;
    if (missing.length) outcome = { status: STATUS.environment, reason: missing.join('; ') };
    else {
      say(`${id}: running`);
      const context = { scripts, logDir, pack: audit.parent.pack, options: { native: 'run' }, run: { gateStart }, gateStart };
      outcome = id === 'native' ? await runNative(gate, context) : afterGate(gate, await runCommandGate(gate, context), { pack: audit.parent.pack, gateStart, browsers: environment.browsers });
    }
    results.set(id, { id, label: gate.label, pack: audit.parent.pack.manifestSha256, ...outcome, execution: 'rerun', startedAt: new Date(gateStart).toISOString(), durationMs: Date.now() - gateStart });
    say(`${id}: ${outcome.status}${outcome.reason ? ` — ${outcome.reason}` : ''}`);
  }
  ensureFrozen(audit);
  const gates = STEP_IDS.map(id => results.get(id));
  assert(gates.every(Boolean), 'Resume omitted a required gate');
  const status = overallStatus(gates, false), verification = {
    schema: SCHEMA, runId, generatedAt: new Date().toISOString(), startedAt: new Date(started).toISOString(), durationMs: Date.now() - started,
    command: ['node scripts/study-harness/resume-release.mjs', ...argv].join(' '), mode: 'resumed-full-candidate', status, partial: false, releaseEvidence: status === 'pass',
    selection: { only: null, skip: null, native: 'run', allowEnvironmentGaps: false },
    source: sourceIdentity(ROOT), packageLock: lockIdentity(ROOT), tools: environment.tools, browsers: environment.browsers, platform: environment.platform, consoleLocked: environment.consoleLocked,
    pack: audit.parent.pack, summary: summarize(gates), gates, claims: claims(status, environment), logs: path.relative(ROOT, logDir),
    resume: { ...audit.provenance, rerun: [...RERUN_GATES], reused: STEP_IDS.filter(id => !RERUN_GATES.includes(id)), explanation: 'Complete required-gate coverage for the unchanged SDK tarball hashes. Passing unchanged gates retain their original full-run results and provenance; affected gates were executed again. The failed parent remains immutable and is not relabelled as passing.' },
  };
  verification.claims.engineeringGates = status === 'pass' ? `All ${gates.length} effective automated gates pass for the identified six-package pack. ${RERUN_GATES.length} affected gates ran again; ${gates.length - RERUN_GATES.length} passing gates were reused with audited parent provenance.` : `Not established by this resumed verification (overall status: ${status}).`;
  writeFileSync(at(ROOT, `${OUT}/verification.json`), `${JSON.stringify(verification, null, 2)}\n`);
  const history = writeHistoryRecord(at(ROOT, OUT), 'verification', verification, { identity: {} });
  const durable = writeHistoryRecord(at(ROOT, EVIDENCE), 'verification', verification, { identity: {} });
  say(`overall: ${status}; ${gates.filter(row => row.execution === 'rerun').length} rerun, ${gates.filter(row => row.execution === 'reused').length} reused; history ${path.relative(ROOT, history)}, ${path.relative(ROOT, durable)}`);
  return { verification, exitCode: status === 'pass' ? 0 : status === 'fail' ? 1 : 2 };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { const { exitCode } = await main(); process.exitCode = exitCode; }
  catch (error) { console.error(`[release-resume] ${error.message}`); process.exitCode = 1; }
}
